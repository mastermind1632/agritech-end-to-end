-- V4: farm business-building companion. Intake answers, the guidance content (editable by admins, with a
-- source link and review status on every item), the farmer's personal checklist, compliance calendar and crop plans.

CREATE TABLE IF NOT EXISTS business_profiles (
    farmer_id                varchar(36)    PRIMARY KEY REFERENCES farmers (id) ON DELETE CASCADE,
    legal_structure          varchar(30)    NOT NULL DEFAULT 'NONE',
    business_name            varchar(150),
    registration_number      varchar(40),
    registered_on            date,
    tax_number               varchar(20),
    vat_registered           boolean        NOT NULL DEFAULT false,
    vat_number               varchar(20),
    employees                integer        NOT NULL DEFAULT 0,
    turnover_band            varchar(20)    NOT NULL DEFAULT 'UNDER_50K',
    crops                    varchar(300),
    hectares                 numeric(10, 2),
    livestock                boolean        NOT NULL DEFAULT false,
    water_source             varchar(30),
    irrigates                boolean        NOT NULL DEFAULT false,
    uses_agrochemicals       boolean        NOT NULL DEFAULT false,
    sells_to_retailers       boolean        NOT NULL DEFAULT false,
    export_interest          boolean        NOT NULL DEFAULT false,
    has_business_account     boolean        NOT NULL DEFAULT false,
    financial_year_end_month integer        NOT NULL DEFAULT 2,
    province                 varchar(40),
    verified                 boolean        NOT NULL DEFAULT false,
    verified_at              timestamp(6),
    verified_by              varchar(36),
    intake_completed_at      timestamp(6),
    updated_at               timestamp(6)   NOT NULL
);

CREATE TABLE IF NOT EXISTS companion_steps (
    code           varchar(40)   PRIMARY KEY,
    stage          integer       NOT NULL,
    stage_name     varchar(60)   NOT NULL,
    title          varchar(150)  NOT NULL,
    description    varchar(2000) NOT NULL,
    why            varchar(1000),
    authority      varchar(80),
    rule_key       varchar(80)   NOT NULL DEFAULT 'ALWAYS',
    link_url       varchar(300),
    link_label     varchar(80),
    module_link    varchar(30),
    sort_order     integer       NOT NULL DEFAULT 0,
    active         boolean       NOT NULL DEFAULT true,
    review_status  varchar(20)   NOT NULL DEFAULT 'DRAFT',
    last_verified  date,
    verified_by    varchar(36),
    updated_at     timestamp(6)  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS companion_tasks (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id    varchar(36)  NOT NULL REFERENCES farmers (id) ON DELETE CASCADE,
    step_code    varchar(40)  NOT NULL REFERENCES companion_steps (code) ON DELETE CASCADE,
    status       varchar(20)  NOT NULL DEFAULT 'TODO',
    note         varchar(500),
    document_id  varchar(36),
    completed_at timestamp(6),
    updated_at   timestamp(6) NOT NULL,
    CONSTRAINT uk_companion_task UNIQUE (farmer_id, step_code)
);

CREATE TABLE IF NOT EXISTS compliance_deadlines (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id   varchar(36)  NOT NULL REFERENCES farmers (id) ON DELETE CASCADE,
    code        varchar(60)  NOT NULL,
    title       varchar(200) NOT NULL,
    due_date    date         NOT NULL,
    authority   varchar(80),
    source_url  varchar(300),
    estimated   boolean      NOT NULL DEFAULT false,
    custom      boolean      NOT NULL DEFAULT false,
    status      varchar(20)  NOT NULL DEFAULT 'UPCOMING',
    reminded_30 boolean      NOT NULL DEFAULT false,
    reminded_7  boolean      NOT NULL DEFAULT false,
    reminded_1  boolean      NOT NULL DEFAULT false,
    document_id varchar(36),
    created_at  timestamp(6) NOT NULL,
    updated_at  timestamp(6) NOT NULL,
    CONSTRAINT uk_compliance_deadline UNIQUE (farmer_id, code, due_date)
);
CREATE INDEX IF NOT EXISTS idx_compliance_deadlines_due ON compliance_deadlines (status, due_date);

CREATE TABLE IF NOT EXISTS crop_plans (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id      varchar(36)    NOT NULL REFERENCES farmers (id) ON DELETE CASCADE,
    crop           varchar(60)    NOT NULL,
    hectares       numeric(10, 2) NOT NULL,
    yield_per_ha   numeric(12, 2) NOT NULL,
    yield_unit     varchar(20)    NOT NULL,
    expected_price numeric(12, 2),
    cost_per_ha    numeric(12, 2),
    plant_month    integer        NOT NULL,
    harvest_month  integer        NOT NULL,
    created_at     timestamp(6)   NOT NULL,
    updated_at     timestamp(6)   NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_crop_plans_farmer ON crop_plans (farmer_id);

