-- Adds a foreign key only if it is missing. NOT VALID: enforced for new rows without failing on
-- historic rows that a previous ddl-auto=update database may contain.
CREATE OR REPLACE FUNCTION pg_temp.add_fk(tbl text, cname text, def text) RETURNS void AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = cname) THEN
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I %s NOT VALID', tbl, cname, def);
    END IF;
END
$$ LANGUAGE plpgsql;

