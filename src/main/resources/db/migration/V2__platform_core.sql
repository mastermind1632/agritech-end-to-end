    id         varchar(36)  PRIMARY KEY,
    farmer_id  varchar(36)  NOT NULL REFERENCES farmers (id) ON DELETE CASCADE,
    token_hash varchar(64)  NOT NULL UNIQUE,
    expires_at timestamp(6) NOT NULL,
    used_at    timestamp(6),
    created_at timestamp(6) NOT NULL
);

-- ---------------------------------------------------------------- audit log (append only)
CREATE TABLE IF NOT EXISTS audit_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    varchar(36),
    action      varchar(60)  NOT NULL,
    entity_type varchar(40),
    entity_id   varchar(64),
    detail      varchar(500),
    ip          varchar(64),
    created_at  timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_log_created ON audit_log (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_log_actor ON audit_log (actor_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_entity ON audit_log (entity_type, entity_id);

-- ---------------------------------------------------------------- notifications for every user
CREATE TABLE IF NOT EXISTS user_notifications (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id varchar(36)  NOT NULL REFERENCES farmers (id) ON DELETE CASCADE,
    category     varchar(30)  NOT NULL,
    title        varchar(150) NOT NULL,
    body         varchar(1000),
    link         varchar(100),
    is_read      boolean      NOT NULL DEFAULT false,
    created_at   timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_user_notifications_recipient ON user_notifications (recipient_id, is_read, created_at DESC);

CREATE TABLE IF NOT EXISTS notification_preferences (
    farmer_id  varchar(36)  PRIMARY KEY REFERENCES farmers (id) ON DELETE CASCADE,
    in_app     boolean      NOT NULL DEFAULT true,
    email      boolean      NOT NULL DEFAULT true,
    sms        boolean      NOT NULL DEFAULT false,
    whatsapp   boolean      NOT NULL DEFAULT false,
    updated_at timestamp(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS notification_deliveries (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id bigint       NOT NULL REFERENCES user_notifications (id) ON DELETE CASCADE,
    channel         varchar(20)  NOT NULL,
    status          varchar(20)  NOT NULL,
    detail          varchar(300),
    created_at      timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_notification_deliveries_notification ON notification_deliveries (notification_id);

-- ---------------------------------------------------------------- POPIA
