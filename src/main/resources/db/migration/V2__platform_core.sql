    expires_on    date,
    linked_module varchar(20),
    linked_ref    varchar(64),
    created_at    timestamp(6) NOT NULL,
    updated_at    timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_vault_documents_owner ON vault_documents (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_vault_documents_link ON vault_documents (linked_module, linked_ref);
CREATE INDEX IF NOT EXISTS idx_vault_documents_expiry ON vault_documents (expires_on) WHERE expires_on IS NOT NULL;

