-- V5: PPECB export readiness. A requirements database where every requirement is tagged with the authority
-- it comes from, linked to a product (and HS code) and destination, with an official source link and a review
-- status. Generating a checklist is a query on product + destination. Each shipment is a workflow instance.

CREATE TABLE IF NOT EXISTS export_products (
    code     varchar(40)  PRIMARY KEY,
    name     varchar(100) NOT NULL,
    hs_code  varchar(20),
    category varchar(40),
    active   boolean      NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS export_destinations (
    code   varchar(20)  PRIMARY KEY,
    name   varchar(100) NOT NULL,
    region varchar(60),
    active boolean      NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS export_requirements (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             varchar(60)   NOT NULL UNIQUE,
    product_code     varchar(40)   REFERENCES export_products (code),
    destination_code varchar(20)   REFERENCES export_destinations (code),
    stage            integer       NOT NULL,
    authority        varchar(30)   NOT NULL,
    title            varchar(200)  NOT NULL,
    description      varchar(2000) NOT NULL,
    documents        varchar(500),
    lead_time_days   integer,
    est_cost         varchar(80),
    source_url       varchar(300),
    review_status    varchar(20)   NOT NULL DEFAULT 'DRAFT',
    last_verified    date,
    verified_by      varchar(36),
    version          integer       NOT NULL DEFAULT 1,
    active           boolean       NOT NULL DEFAULT true,
    source_hash      varchar(64),
    source_checked_at timestamp(6),
    updated_at       timestamp(6)  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_export_requirements_pair ON export_requirements (product_code, destination_code);

-- Detected or proposed changes wait here for a compliance editor. Nothing scraped is ever published automatically.
CREATE TABLE IF NOT EXISTS export_requirement_changes (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requirement_id   bigint        NOT NULL REFERENCES export_requirements (id) ON DELETE CASCADE,
    source           varchar(20)   NOT NULL,
    summary          varchar(500)  NOT NULL,
    proposed_title   varchar(200),
    proposed_description varchar(2000),
    status           varchar(20)   NOT NULL,
    proposed_by      varchar(36),
    reviewed_by      varchar(36),
    reviewed_at      timestamp(6),
    created_at       timestamp(6)  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_export_changes_status ON export_requirement_changes (status, created_at DESC);

CREATE TABLE IF NOT EXISTS export_workflows (
    id               varchar(36)    PRIMARY KEY,
    farmer_id        varchar(36)    NOT NULL REFERENCES farmers (id) ON DELETE CASCADE,
    product_code     varchar(40)    NOT NULL REFERENCES export_products (code),
    destination_code varchar(20)    NOT NULL REFERENCES export_destinations (code),
    current_stage    integer        NOT NULL DEFAULT 1,
    status           varchar(20)    NOT NULL,
    target_ship_date date,
    volume           numeric(12, 2),
    volume_unit      varchar(20),
    outcome          varchar(1000),
    lessons          varchar(1000),
    created_at       timestamp(6)   NOT NULL,
    updated_at       timestamp(6)   NOT NULL,
    closed_at        timestamp(6)
);
CREATE INDEX IF NOT EXISTS idx_export_workflows_farmer ON export_workflows (farmer_id);

CREATE TABLE IF NOT EXISTS export_workflow_items (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id         varchar(36)  NOT NULL REFERENCES export_workflows (id) ON DELETE CASCADE,
    requirement_id      bigint       NOT NULL REFERENCES export_requirements (id),
    status              varchar(20)  NOT NULL DEFAULT 'TODO',
    note                varchar(500),
    document_id         varchar(36),
    requirement_version integer      NOT NULL,
    completed_at        timestamp(6),
    updated_at          timestamp(6) NOT NULL,
    CONSTRAINT uk_export_item UNIQUE (workflow_id, requirement_id)
);

