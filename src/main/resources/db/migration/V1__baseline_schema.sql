-- V1: the schema that Hibernate's ddl-auto=update created before Flyway was introduced.
-- Fresh databases get it from here. Existing databases are "baselined" at version 1 (V1 is skipped)
-- because spring.flyway.baseline-on-migrate=true, and only V2+ run on them.
-- Column types and lengths match the JPA entities so spring.jpa.hibernate.ddl-auto=validate passes.

CREATE TABLE IF NOT EXISTS farmers (
    id            varchar(36)  PRIMARY KEY,
    name          varchar(150) NOT NULL,
    location      varchar(150),
    contact       varchar(100) UNIQUE,
    password_hash varchar(255),
    role          varchar(20),
    created_at    timestamp(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS farmer_avatars (
    farmer_id    varchar(36)  PRIMARY KEY,
    content_type varchar(50)  NOT NULL,
    data         bytea        NOT NULL,
    updated_at   timestamp(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS suppliers (
    id       varchar(36)  PRIMARY KEY,
    name     varchar(150) NOT NULL,
    location varchar(150),
    contact  varchar(100)
);

CREATE TABLE IF NOT EXISTS supplier_products (
    id             varchar(36)    PRIMARY KEY,
    supplier_id    varchar(36)    NOT NULL,
    product_name   varchar(150)   NOT NULL,
    price          numeric(12, 2) NOT NULL,
    comparison_key varchar(150),
    pack_size      numeric(12, 3),
    pack_unit      varchar(10)
);

CREATE TABLE IF NOT EXISTS group_orders (
    id               varchar(36)   PRIMARY KEY,
    product_id       varchar(36)   NOT NULL,
    status           varchar(50)   NOT NULL,
    target_quantity  integer       NOT NULL,
    current_quantity integer       NOT NULL,
    discount_rate    numeric(5, 2),
    created_at       timestamp(6)  NOT NULL
);

CREATE TABLE IF NOT EXISTS group_order_items (
    id             varchar(36)    PRIMARY KEY,
    group_order_id varchar(36)    NOT NULL,
    farmer_id      varchar(36)    NOT NULL,
    quantity       integer        NOT NULL,
    total_price    numeric(12, 2) NOT NULL,
    joined_at      timestamp(6)   NOT NULL
);

CREATE TABLE IF NOT EXISTS notifications (
    id             varchar(36)  PRIMARY KEY,
    supplier_id    varchar(36)  NOT NULL,
    group_order_id varchar(36),
    message        text         NOT NULL,
    is_read        boolean      NOT NULL,
    created_at     timestamp(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS expenses (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id varchar(36)    NOT NULL,
    item      varchar(150)   NOT NULL,
    category  varchar(100),
    amount    numeric(12, 2) NOT NULL,
    date      date           NOT NULL
);

CREATE TABLE IF NOT EXISTS income (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id varchar(36)    NOT NULL,
    item      varchar(150)   NOT NULL,
    amount    numeric(12, 2) NOT NULL,
    date      date           NOT NULL
);

CREATE TABLE IF NOT EXISTS ai_recommendations (
    id                       varchar(36)  PRIMARY KEY,
    farmer_id                varchar(36)  NOT NULL,
    recommended_product_id   varchar(36),
    suggested_group_order_id varchar(36),
    reason                   text         NOT NULL,
    created_at               timestamp(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id         varchar(36)   PRIMARY KEY,
    room       varchar(120)  NOT NULL,
    sender_id  varchar(36)   NOT NULL,
    body       varchar(1000) NOT NULL,
    created_at timestamp(6)  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_chat_room_time ON chat_messages (room, created_at);

CREATE TABLE IF NOT EXISTS market_listings (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id          varchar(36)    NOT NULL,
    product            varchar(100)   NOT NULL,
    category           varchar(50),
    grade              varchar(30),
    unit               varchar(20)    NOT NULL,
    price_per_unit     numeric(12, 2) NOT NULL,
    quantity_available numeric(12, 2) NOT NULL,
    cost_per_unit      numeric(12, 2),
    sale_price         numeric(12, 2),
    sale_ends_on       date,
    available_from     date,
    available_until    date,
    description        varchar(1000),
    location           varchar(150),
    latitude           float(53),
    longitude          float(53),
    status             varchar(20)    NOT NULL,
    created_at         timestamp(6)   NOT NULL,
    updated_at         timestamp(6)   NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_market_listings_seller ON market_listings (seller_id);
CREATE INDEX IF NOT EXISTS idx_market_listings_status ON market_listings (status);

CREATE TABLE IF NOT EXISTS market_listing_images (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id   bigint       NOT NULL,
    content_type varchar(50)  NOT NULL,
    data         bytea        NOT NULL,
    created_at   timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_market_listing_images_listing ON market_listing_images (listing_id);

CREATE TABLE IF NOT EXISTS market_orders (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id            bigint         NOT NULL,
    buyer_id              varchar(36)    NOT NULL,
    seller_id             varchar(36)    NOT NULL,
    product               varchar(100)   NOT NULL,
    unit                  varchar(20)    NOT NULL,
    price_per_unit        numeric(12, 2) NOT NULL,
    quantity              numeric(12, 2) NOT NULL,
    total_amount          numeric(12, 2) NOT NULL,
    cost_total            numeric(12, 2),
    status                varchar(20)    NOT NULL,
    delivery_note         varchar(500),
    delivery_code         varchar(6),
    code_attempts         integer        NOT NULL,
    stock_reserved        boolean        NOT NULL,
    buyer_confirmed_paid  boolean        NOT NULL,
    seller_confirmed_paid boolean        NOT NULL,
    delivered_lat         float(53),
    delivered_lng         float(53),
    created_at            timestamp(6)   NOT NULL,
    updated_at            timestamp(6)   NOT NULL,
    confirmed_at          timestamp(6),
    dispatched_at         timestamp(6),
    delivered_at          timestamp(6),
    completed_at          timestamp(6)
);
CREATE INDEX IF NOT EXISTS idx_market_orders_buyer ON market_orders (buyer_id);
CREATE INDEX IF NOT EXISTS idx_market_orders_seller ON market_orders (seller_id);

CREATE TABLE IF NOT EXISTS market_order_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    bigint       NOT NULL,
    actor_id    varchar(36),
    from_status varchar(20),
    to_status   varchar(20)  NOT NULL,
    note        varchar(300),
    created_at  timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_market_order_events_order ON market_order_events (order_id);

CREATE TABLE IF NOT EXISTS market_reviews (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type varchar(20)  NOT NULL,
    target_id   varchar(36)  NOT NULL,
    reviewer_id varchar(36)  NOT NULL,
    order_id    bigint,
    rating      integer      NOT NULL,
    comment     varchar(500),
    created_at  timestamp(6) NOT NULL,
    updated_at  timestamp(6) NOT NULL,
    CONSTRAINT uk_market_review_once UNIQUE (reviewer_id, target_type, target_id, order_id)
);
CREATE INDEX IF NOT EXISTS idx_market_reviews_target ON market_reviews (target_type, target_id);
