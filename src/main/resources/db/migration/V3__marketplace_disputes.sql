-- V3: marketplace disputes. Either side can raise one within the dispute window; the other side responds;
-- an administrator resolves it and every step is logged on the order's event trail.

CREATE TABLE IF NOT EXISTS market_disputes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        bigint        NOT NULL REFERENCES market_orders (id) ON DELETE CASCADE,
    raised_by       varchar(36)   NOT NULL REFERENCES farmers (id),
    against_id      varchar(36)   NOT NULL REFERENCES farmers (id),
    reason          varchar(30)   NOT NULL,
    description     varchar(1000) NOT NULL,
    status          varchar(20)   NOT NULL,
    previous_status varchar(20)   NOT NULL,
    respond_by      timestamp(6)  NOT NULL,
    response        varchar(1000),
    responded_at    timestamp(6),
    resolution      varchar(30),
    resolution_note varchar(1000),
    resolved_by     varchar(36),
    resolved_at     timestamp(6),
    created_at      timestamp(6)  NOT NULL,
    updated_at      timestamp(6)  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_market_disputes_order ON market_disputes (order_id);
CREATE INDEX IF NOT EXISTS idx_market_disputes_status ON market_disputes (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_market_disputes_parties ON market_disputes (raised_by, against_id);
-- Only one open dispute per order at a time.
CREATE UNIQUE INDEX IF NOT EXISTS uk_market_disputes_open ON market_disputes (order_id)
    WHERE status IN ('OPEN', 'RESPONDED');
