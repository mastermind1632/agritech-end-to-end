-- V6: bank statement upload, extraction, categorisation and analysis (module 5).

CREATE TABLE IF NOT EXISTS bank_statements (
    id                varchar(36)    PRIMARY KEY,
    farmer_id         varchar(36)    NOT NULL REFERENCES farmers (id) ON DELETE CASCADE,
    file_name         varchar(200)   NOT NULL,
    source_type       varchar(20)    NOT NULL,
    extraction_method varchar(20),
    bank              varchar(40),
    account_hint      varchar(8),
    period_start      date,
    period_end        date,
    opening_balance   numeric(14, 2),
    closing_balance   numeric(14, 2),
    computed_closing  numeric(14, 2),
    balance_check     varchar(10)    NOT NULL DEFAULT 'UNKNOWN',
    status            varchar(20)    NOT NULL,
    message           varchar(1000),
    transaction_count integer        NOT NULL DEFAULT 0,
    original_document_id varchar(36),
    consent_id        bigint,
    created_at        timestamp(6)   NOT NULL,
    confirmed_at      timestamp(6)
);
CREATE INDEX IF NOT EXISTS idx_bank_statements_farmer ON bank_statements (farmer_id, created_at DESC);

CREATE TABLE IF NOT EXISTS statement_transactions (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id      varchar(36)    NOT NULL REFERENCES bank_statements (id) ON DELETE CASCADE,
    farmer_id         varchar(36)    NOT NULL REFERENCES farmers (id) ON DELETE CASCADE,
    txn_date          date           NOT NULL,
    description       varchar(300)   NOT NULL,
    amount            numeric(14, 2) NOT NULL,
    balance           numeric(14, 2),
    category          varchar(30)    NOT NULL,
    confidence        float(53)      NOT NULL,
    category_source   varchar(20)    NOT NULL,
    needs_review      boolean        NOT NULL DEFAULT false,
    direction_certain boolean        NOT NULL DEFAULT true,
    crop              varchar(60),
    flag              varchar(20),
    flag_reason       varchar(300),
    matched_order_id  bigint,
    ledger_type       varchar(10),
    ledger_id         bigint,
    created_at        timestamp(6)   NOT NULL,
    updated_at        timestamp(6)   NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_statement_txns_statement ON statement_transactions (statement_id, txn_date);
CREATE INDEX IF NOT EXISTS idx_statement_txns_farmer ON statement_transactions (farmer_id, txn_date);

-- The farmer's own corrections ("ENGEN TZANEEN is Fuel"). They become training data and always win next time.
CREATE TABLE IF NOT EXISTS category_memory (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id    varchar(36)  NOT NULL REFERENCES farmers (id) ON DELETE CASCADE,
    merchant_key varchar(100) NOT NULL,
    category     varchar(30)  NOT NULL,
    uses         integer      NOT NULL DEFAULT 1,
    updated_at   timestamp(6) NOT NULL,
    CONSTRAINT uk_category_memory UNIQUE (farmer_id, merchant_key)
);

-- How untagged costs are spread over crops, e.g. fertiliser split by hectares planted.
CREATE TABLE IF NOT EXISTS allocation_rules (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id  varchar(36)  NOT NULL REFERENCES farmers (id) ON DELETE CASCADE,
    category   varchar(30)  NOT NULL,
    method     varchar(20)  NOT NULL,
    crop       varchar(60),
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_allocation_rule UNIQUE (farmer_id, category)
);
